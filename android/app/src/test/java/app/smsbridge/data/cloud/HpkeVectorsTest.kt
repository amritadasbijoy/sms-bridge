package app.smsbridge.data.cloud

import java.io.File
import java.util.Base64
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Writes testdata/hpke-vectors-v1.json: vault keys wrapped by the phone's real (Tink) HPKE for a
 * browser's X25519 key, which web/test/hpke.test.ts must unwrap. Recreated only when missing.
 * The private key in the file is a throwaway test key that protects nothing.
 */
class HpkeVectorsTest {
    private val file = File("../../testdata/hpke-vectors-v1.json")
    private val b64 = Base64.getEncoder()
    private val dec = Base64.getDecoder()

    @Test
    fun vectorsExistAndUnwrap() {
        if (!file.exists()) generate()
        val text = file.readText()
        fun field(name: String) = Regex("\"$name\": \"([^\"]+)\"").find(text)!!.groupValues[1]
        val keys = DeviceKeys(dec.decode(field("encPrivate")), dec.decode(field("encPublic")), ByteArray(32), dec.decode(field("signPublic")))
        val recipient = field("recipientId")
        val cases = Regex("\\{\"keyVersion\": (\\d+), \"vaultKey\": \"([^\"]+)\", \"wrapped\": \"([^\"]+)\"\\}").findAll(text).toList()
        assertTrue(cases.size == 2)
        for (c in cases) {
            val (version, vk, wrapped) = c.destructured
            assertArrayEquals(dec.decode(vk), CloudCrypto.unwrapForDevice(dec.decode(wrapped), keys, recipient, version.toInt()))
        }
    }

    private fun generate() {
        val browser = DeviceKeys.generate()
        val recipient = "b0000000-0000-4000-8000-00000000web1"
        val cases = (1..2).map { v ->
            val vk = CloudCrypto.newVaultKey()
            "    {\"keyVersion\": $v, \"vaultKey\": \"${b64.encodeToString(vk)}\", \"wrapped\": \"${b64.encodeToString(CloudCrypto.wrapForDevice(vk, browser.encPublic, recipient, v))}\"}"
        }
        file.parentFile!!.mkdirs()
        file.writeText(
            "{\n  \"note\": \"Generated by HpkeVectorsTest (Android CloudCrypto / Tink HPKE). Throwaway test keys.\",\n" +
                "  \"recipientId\": \"$recipient\",\n" +
                "  \"encPrivate\": \"${b64.encodeToString(browser.encPrivate)}\",\n" +
                "  \"encPublic\": \"${b64.encodeToString(browser.encPublic)}\",\n" +
                "  \"signPublic\": \"${b64.encodeToString(browser.signPublic)}\",\n" +
                "  \"safetyCode\": \"${CloudCrypto.safetyCode(browser.encPublic, browser.signPublic)}\",\n" +
                "  \"cases\": [\n${cases.joinToString(",\n")}\n  ]\n}\n",
        )
    }
}
