package app.smsbridge.data.cloud

import java.io.File
import java.util.Base64
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Writes testdata/sync-vectors-v1.json, made by the phone's real CloudCrypto, which the web
 * dashboard's tests (web/test/vectors.test.ts) must decrypt. The file is committed; this test
 * re-verifies it on every run and recreates it only when it is missing. Synthetic content only.
 */
class CrossLanguageVectorsTest {
    private val file = File("../../testdata/sync-vectors-v1.json")
    private val b64 = Base64.getEncoder()

    private fun payload(type: String, messageId: String, address: String, body: String, date: Long, box: String, read: Boolean) =
        """{"v":1,"type":"$type","messageId":"$messageId","address":${jsonString(address)},"body":${jsonString(body)},"date":$date,"dateSent":$date,""" +
            """"box":"$box","read":$read,"seen":$read,"status":null,"sub":1,"src":null}"""

    private fun jsonString(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n") + "\""

    private fun sha256(b: ByteArray) = java.security.MessageDigest.getInstance("SHA-256").digest(b).joinToString("") { "%02x".format(it) }

    @Test
    fun vectorsExistAndDecryptWithTheRecoveryKey() {
        if (!file.exists()) generate()
        val text = file.readText()
        val recoveryKey = Regex("\"recoveryKey\": \"([^\"]+)\"").find(text)!!.groupValues[1]
        val wrapped = Regex("\"wrappedKey\": \"([^\"]+)\"").find(text)!!.groupValues[1]
        val vk = CloudCrypto.unwrapForRecovery(Base64.getDecoder().decode(wrapped), CloudCrypto.parseRecoveryKey(recoveryKey)!!, 1)
        val events = Regex(
            "\\{\"eventId\": \"([^\"]+)\", \"deviceId\": \"([^\"]+)\", \"deviceSequence\": (\\d+), \"serverSequence\": \\d+, " +
                "\"keyVersion\": 1, \"ciphertext\": \"([^\"]+)\", \"valid\": (true|false), \"plaintextSha256\": \"([0-9a-f]*)\"",
        ).findAll(text).toList()
        assertEquals(5, events.size)
        for (m in events) {
            val (eventId, deviceId, seq, ct, valid, plainSha) = m.destructured
            val result = runCatching { CloudCrypto.decryptEvent(vk, Base64.getDecoder().decode(ct), eventId, deviceId, seq.toLong(), 1) }
            assertEquals(valid.toBoolean(), result.isSuccess)
            if (result.isSuccess) assertEquals(plainSha, sha256(result.getOrThrow()))
        }
        val enc = Regex("\"encPublic\": \"([^\"]+)\"").find(text)!!.groupValues[1]
        val sign = Regex("\"signPublic\": \"([^\"]+)\"").find(text)!!.groupValues[1]
        val code = Regex("\"code\": \"([^\"]+)\"").find(text)!!.groupValues[1]
        assertEquals(code, CloudCrypto.safetyCode(Base64.getDecoder().decode(enc), Base64.getDecoder().decode(sign)))
    }

    private fun generate() {
        val recovery = CloudCrypto.newRecoveryKey()
        val vk = CloudCrypto.newVaultKey()
        val phoneA = "0d6c2f7e-1111-4a8e-9a51-6f1c2b3a4d5e"
        val phoneB = "5b9e8a2c-2222-4f3d-8c7b-1a2b3c4d5e6f"
        val t = 1_767_225_600_000L // 2026-01-01T00:00:00Z
        data class Ev(val id: String, val device: String, val seq: Long, val plain: String, val tamper: Boolean = false)
        val evs = listOf(
            Ev("e0000000-0000-4000-8000-000000000001", phoneA, 1, payload("SMS_RECEIVED", "m-a-1", "+15555550101", "Synthetic \"hello\" from A\nline two", t, "INBOX", false)),
            Ev("e0000000-0000-4000-8000-000000000002", phoneA, 2, payload("SMS_SENT", "m-a-2", "+15555550101", "Synthetic reply", t + 60_000, "SENT", true)),
            // Newer state for m-a-1: now read.
            Ev("e0000000-0000-4000-8000-000000000003", phoneA, 3, payload("SMS_STATUS_CHANGED", "m-a-1", "+15555550101", "Synthetic \"hello\" from A\nline two", t, "INBOX", true)),
            // The same SMS uploaded by a second phone (e.g. after a Wi-Fi transfer), national format.
            Ev("e0000000-0000-4000-8000-000000000004", phoneB, 1, payload("SMS_IMPORTED", "m-b-9", "5555550101", "Synthetic \"hello\" from A\nline two", t, "INBOX", false)),
            // Ciphertext altered after encryption: must be rejected.
            Ev("e0000000-0000-4000-8000-000000000005", phoneB, 2, payload("SMS_RECEIVED", "m-b-10", "ACME", "Synthetic tampered", t + 120_000, "INBOX", false), tamper = true),
        )
        val keys = DeviceKeys.generate()
        val sb = StringBuilder()
        sb.append("{\n  \"note\": \"Generated by CrossLanguageVectorsTest (Android CloudCrypto). Synthetic data only; the keys here protect nothing.\",\n")
        sb.append("  \"recoveryKey\": \"${CloudCrypto.formatRecoveryKey(recovery)}\",\n")
        sb.append("  \"recoveryKeys\": [{\"keyVersion\": 1, \"wrappedKey\": \"${b64.encodeToString(CloudCrypto.wrapForRecovery(vk, recovery, 1))}\"}],\n")
        sb.append("  \"events\": [\n")
        evs.forEachIndexed { i, e ->
            val ct = CloudCrypto.encryptEvent(vk, e.plain.toByteArray(Charsets.UTF_8), e.id, e.device, e.seq, 1)
            if (e.tamper) ct[ct.size - 20] = (ct[ct.size - 20].toInt() xor 1).toByte()
            sb.append("    {\"eventId\": \"${e.id}\", \"deviceId\": \"${e.device}\", \"deviceSequence\": ${e.seq}, \"serverSequence\": ${i + 1}, ")
            sb.append("\"keyVersion\": 1, \"ciphertext\": \"${b64.encodeToString(ct)}\", \"valid\": ${!e.tamper}, ")
            sb.append("\"plaintextSha256\": \"${if (e.tamper) "" else sha256(e.plain.toByteArray(Charsets.UTF_8))}\", ")
            sb.append("\"plaintext\": ${if (e.tamper) "null" else jsonString(e.plain)}}")
            sb.append(if (i < evs.size - 1) ",\n" else "\n")
        }
        sb.append("  ],\n")
        sb.append("  \"safetyCode\": {\"encPublic\": \"${b64.encodeToString(keys.encPublic)}\", \"signPublic\": \"${b64.encodeToString(keys.signPublic)}\", ")
        sb.append("\"code\": \"${CloudCrypto.safetyCode(keys.encPublic, keys.signPublic)}\"}\n}\n")
        file.parentFile!!.mkdirs()
        file.writeText(sb.toString())
        assertTrue(file.exists())
        assertArrayEquals(vk, CloudCrypto.unwrapForRecovery(CloudCrypto.wrapForRecovery(vk, recovery, 1), recovery, 1))
    }
}
